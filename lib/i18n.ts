export type MessageKey = keyof typeof messages.en;

function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, key) => String(params[key] ?? ""));
}

export function translate(locale: Locale, key: MessageKey, params?: Record<string, string | number>) {
  const entry = (messages[locale] as Record<string, string | undefined>)[key] ?? messages.en[key];
  if (!entry) return key;
  return interpolate(entry, params);
}

export function resolveLocale(raw?: string | null): Locale {
  return raw?.toLowerCase() === "ar" ? "ar" : "en";
}

export const supportedLocales: Locale[] = ["en", "ar"];
